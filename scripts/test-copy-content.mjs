import assert from 'node:assert/strict';
import { parseHTML } from 'linkedom';
import { readFileSync } from 'node:fs';
import { messageCopyContent } from './copy-controls.mjs';
import { conversationToMarkdownView } from './conversation-to-markdown-view.mjs';
const document = parseHTML('<html></html>').document;
const conversation = JSON.parse(readFileSync('fixtures/chatgpt-share/6a9849f6-3bec-83ee-b032-618d95fc0917/conversation.ceobe.json', 'utf8'));
const copies = conversationToMarkdownView(conversation).filter(m => m.role === 'assistant').map(m => messageCopyContent(m.parts, document));
const chart = copies.find(c => c.text.includes('题目分值分布'));
assert.ok(chart.text.includes('210') && chart.text.includes('30') && chart.text.includes('24'));
assert.ok(chart.html.includes('<table>'));
const cited = copies.find(c => c.text.includes('Privacy Portal'));
assert.ok(cited.text.includes('https://help.openai.com'));
assert.ok(cited.html.includes('<a href="https://help.openai.com'));
const malicious = messageCopyContent([{ type: 'markdown', markdown: '<script>alert(1)</script>\n\n[bad](javascript:alert)\n\n\\(x^2\\)', contentReferences: [] }], document);
const parsed = parseHTML(malicious.html).document;
assert.equal(parsed.querySelector('script'), null);
assert.equal(parsed.querySelector('a').getAttribute('href'), null);
assert.ok(malicious.html.includes('\\(x^2\\)'));
assert.ok(copies.every(c => !c.text.includes('\uE200')));
console.log('Real sample citations, chart data, HTML safety and TeX preservation passed.');
