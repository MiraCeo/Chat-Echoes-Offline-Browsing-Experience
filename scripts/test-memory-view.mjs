import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const view = JSON.parse(await readFile('data/private/memory-kernel/memory-view.json', 'utf8'));
assert.equal(view.schema, 'ceobe.memory-view/2');
assert.equal(view.archive.total, 35);
assert.deepEqual(view.archive.groups, { gq: 10, g1: 11, 'g-early': 11, 'g-oct': 3 });
assert.equal(view.archive.ungrouped, 0);
assert.equal(view.groups.length, 4);
assert.deepEqual(view.groups.map(group => group.group), ['gq', 'g1', 'g-early', 'g-oct']);
assert.equal(view.groups.find(group => group.group === 'g1').name, '01–10 组');
assert.equal(view.groups.find(group => group.group === 'g1').coverage.sessions, 11);
assert.equal(view.sessions.length, 35);
assert.equal(view.sessions.filter(session => session.staging).length, 5);
assert.ok(view.sessions.every(session => session.l2.html.length > 100));
assert.ok(view.sessions.every(session => session.l4.nodes.length > 0));
assert.ok(view.sessions.every(session => session.round_map.length > 0));
assert.ok(view.sessions.every(session => session.round_map.every(item => item.message_id && item.round > 0)));
assert.ok(view.global.overview.html.length > 1000);
assert.equal(view.ungrouped.count, 0);
assert.equal(view.ungrouped.sessions.length, 0);
assert.equal(view.global.mainlines.length, 13);
assert.equal(view.global.threads.length, 15);
assert.equal(view.global.projects.length, 7);
assert.equal(view.global.conflicts.length, 9);
assert.equal(view.global.thread_docs.length, 12);
assert.equal(view.global.tree.nodes, 500);
assert.equal(view.global.tree.edges, 251);
assert.equal(view.global.tree_data.nodes.length, 500);
assert.equal(view.global.tree_data.edges.length, 251);
// L5 time windows: every edge carries [from, to, type, valid_at, invalid_at];
// superseded nodes carry the ts of the node that overturned them.
assert.ok(view.global.tree_data.edges.every(edge => edge.length === 5));
assert.ok(view.global.tree_data.edges.every(edge => Number.isFinite(edge[3])));
const supersededEdges = view.global.tree_data.edges.filter(edge => edge[2] === 'superseded');
assert.equal(supersededEdges.length, 106);
assert.ok(supersededEdges.every(edge => Number.isFinite(edge[4]) && edge[4] >= edge[3]));
assert.ok(view.global.tree_data.edges.filter(edge => edge[2] !== 'superseded').every(edge => edge[4] === null));
const supersededNodes = view.global.tree_data.nodes.filter(node => node.s === 'superseded');
assert.equal(supersededNodes.length, 106);
assert.ok(supersededNodes.every(node => Number.isFinite(node.invalid_at) && node.invalid_at > node.valid_at));
assert.ok(supersededNodes.every(node => Number.isInteger(node.superseded_by)));
assert.ok(view.global.tree_data.nodes.filter(node => node.s !== 'superseded').every(node => node.invalid_at === null));
assert.ok(view.global.thread_docs.every(doc => doc.html.length > 100));
console.log('PASS memory view: four groups, 35 sessions, global/L5 metadata, no ungrouped');
